function genPartsOfSpeech(n) {
  const pools = {
    Ουσιαστικό: NOUNS.map((x) => x[0]),
    Επίθετο: ADJECTIVES,
    Ρήμα: VERBS.map((x) => x[0]),
    Επίρρημα: ADVERBS,
  }
  const types = Object.keys(pools)
  let made = 0, guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const targetType = pick(types)
    const correctWord = pick(pools[targetType])
    const distractors = types
      .filter((t) => t !== targetType)
      .map((t) => pick(pools[t]))
    const q = `Ποια λέξη είναι ${targetType.toLowerCase()};`
    const opts = shuffle([correctWord, ...distractors])
    if (addQ(grammar, 'grammar', 'multiple-choice', q, correctWord, opts)) made++
  }
}

// ---- ENVIRONMENT ----
function genEnvironment() {
  for (const [q, answer, wrongs] of ENVIRONMENT_QUESTIONS) {
    if (wrongs) {
      addQ(environment, 'environment', 'multiple-choice', q, answer, mcOptions(answer, wrongs))
    } else {
      addQ(environment, 'environment', 'text', q, answer)
    }
  }
}

// ---- SPELLING ----
function genSpelling(n, mcRatio) {
  const withVariants = SPELLING_WORDS.map((w) => ({ w, v: buildSpellingVariants(w) })).filter((x) => x.v)
  let made = 0, guard = 0
  while (made < n && guard < n * 30) {
    guard++
    const entry = pick(withVariants)
    const { correct, wrongs } = entry.v
    const wantMc = rng() < mcRatio && wrongs.length >= 1
    if (wantMc) {
      const distractors = wrongs.length >= 3 ? pickN(wrongs, 3) : [...wrongs, ...pickN(wrongs, 3 - wrongs.length)]
      const q = 'Ποια γραφή είναι σωστή;'
      const opts = mcOptions(correct, distractors)
      if (addQ(spelling, 'spelling', 'multiple-choice', q, correct, opts)) made++
    } else {
      const match = findConfusionMatch(correct)
      const { key, idx } = match
      const blanked = correct.slice(0, idx) + '___' + correct.slice(idx + key.length)
      const q = `Συμπλήρωσε σωστά τη λέξη: ${blanked}`
      if (addQ(spelling, 'spelling', 'text', q, correct)) made++
    }
  }
}

