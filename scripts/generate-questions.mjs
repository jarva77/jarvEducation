// αιτιατική («στον Παρατατικό»), όπως διαβάζεται μέσα στην εκφώνηση
const TENSE_LABELS = ['Ενεστώτα', 'Παρατατικό', 'Αόριστο', 'Μέλλοντα']
function genVerbTenses(n, mcRatio) {
  let made = 0, guard = 0
  while (made < n && guard < n * 30) {
    guard++
    const [base, firstPerson, thirdPerson] = pick(VERBS)
    const tense = randInt(0, 2) // παρατατικός/αόριστος/μέλλοντας
    const answer = firstPerson[tense]
    const q = `Το ρήμα «${base}» στον ${TENSE_LABELS[tense + 1]} γίνεται:`
    const isMc = rng() < mcRatio
    let opts
    if (isMc) {
      const otherVerb = pick(VERBS.filter((v) => v[0] !== base))
      const distractors = [
        ...firstPerson.filter((_, i) => i !== tense),
        otherVerb[1][tense],
      ]
      opts = mcOptions(answer, distractors)
    }
    // text answers in γ' ενικό (e.g. «έπαιξε») are equally correct
    const accepted = isMc ? undefined : [thirdPerson[tense]]
    if (addQ(grammar, 'grammar', isMc ? 'multiple-choice' : 'text', q, answer, opts, accepted)) made++
  }
}

function genSynonyms(n, mcRatio) {
  let made = 0, guard = 0
  while (made < n && guard < n * 30) {
    guard++
    const pair = pick(SYNONYM_PAIRS)
    const reversed = rng() < 0.5
    const [word, syn] = reversed ? [pair[1], pair[0]] : pair
    const extras = pair[2] ?? []
    const isMc = rng() < mcRatio
    const q = isMc ? `Ποιο είναι το συνώνυμο της λέξης «${word}»;` : `Γράψε ένα συνώνυμο της λέξης «${word}».`
    let opts
    if (isMc) {
      const distractorPairs = SYNONYM_PAIRS.filter((p) => p !== pair)
      const distractors = pickN(distractorPairs, 3).map((p) => pick(p.slice(0, 2)))
      opts = mcOptions(syn, distractors)
    }
    // in text mode the extra synonyms also count as correct
    const accepted = isMc ? undefined : extras.filter((w) => w !== syn && w !== word)
    if (addQ(grammar, 'grammar', isMc ? 'multiple-choice' : 'text', q, syn, opts, accepted)) made++
  }
}

