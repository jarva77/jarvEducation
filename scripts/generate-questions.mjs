function genComparisonAndSequence(n, mcRatio) {
  let made = 0, guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const kind = pick(['parity', 'sequence', 'place-value'])
    if (kind === 'parity') {
      const nums = pickN([randInt(10, 99), randInt(10, 99), randInt(10, 99), randInt(10, 99)], 4)
      const odds = nums.filter((x) => x % 2 !== 0)
      if (odds.length === 0 || odds.length === 4) continue
      const target = pick(rng() < 0.5 ? nums.filter((x) => x % 2 !== 0) : nums.filter((x) => x % 2 === 0))
      const isOdd = target % 2 !== 0
      const q = `Ποιος αριθμός είναι ${isOdd ? 'μονός (περιττός)' : 'ζυγός (άρτιος)'};`
      const opts = mcOptions(target, nums.filter((x) => x !== target))
      if (opts.length < 2) continue
      if (addQ(math, 'math', 'multiple-choice', q, target, opts)) made++
    } else if (kind === 'sequence') {
      const step = pick([2, 3, 5, 10])
      const start = randInt(1, 20) * step
      const seq = [start, start + step, start + 2 * step, start + 3 * step, start + 4 * step]
      const missingIdx = randInt(2, 3)
      const answer = seq[missingIdx]
      const display = seq.map((v, i) => (i === missingIdx ? '__' : v)).join(', ')
      const q = `Ποιος αριθμός λείπει: ${display};`
      const isMc = rng() < mcRatio
      const opts = isMc ? mcOptions(answer, [answer + step, answer - step, answer + 1]) : undefined
      if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, answer, opts)) made++
    } else {
      const h = randInt(1, 9)
      const t = randInt(0, 9)
      const u = randInt(0, 9)
      const num = h * 100 + t * 10 + u
      if (num < 100) continue
      const q = `Πόσες εκατοντάδες έχει ο αριθμός ${num};`
      const opts = mcOptions(h, [h + 1, h - 1 >= 0 ? h - 1 : h + 2, t])
      if (addQ(math, 'math', 'multiple-choice', q, h, opts)) made++
    }
  }
}

