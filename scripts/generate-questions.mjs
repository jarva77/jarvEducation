// ---- SPELLING ----
function genSpelling(n, mcRatio, wordList = SPELLING_WORDS) {
  const withVariants = wordList.map((w) => ({ w, v: buildSpellingVariants(w) })).filter((x) => x.v)
  let made = 0, guard = 0
  while (made < n && guard < n * 30) {
    guard++
    const entry = pick(withVariants)
    const { correct, wrongs } = entry.v
    const wantMc = rng() < mcRatio && wrongs.length >= 1
    if (wantMc) {
      const distractors = wrongs.length >= 3 ? pickN(wrongs, 3) : [...wrongs, ...pickN(wrongs, 3 - wrongs.length)]
      const q = 'Ποια γραφή είναι σωστή;'
      const opts = mcOptions(correct, distractors)
      if (addQ(spelling, 'spelling', 'multiple-choice', q, correct, opts)) made++
    } else {
      const match = findConfusionMatch(correct)
      const { key, idx } = match
      // one underscore per missing letter, and the expected answer is
      // just those letters (the full word is accepted too)
      const blanked = correct.slice(0, idx) + '_'.repeat(key.length) + correct.slice(idx + key.length)
      const what = key.length > 1 ? 'τα γράμματα που λείπουν' : 'το γράμμα που λείπει'
      const q = `Συμπλήρωσε ${what}: ${blanked}`
      if (addQ(spelling, 'spelling', 'text', q, key, undefined, [correct])) made++
    }
  }
}

