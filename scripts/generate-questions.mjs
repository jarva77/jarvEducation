function genArticles(n) {
  const chosen = pickN(NOUNS, Math.min(n, NOUNS.length))
  for (const [word, article] of chosen) {
    const q = `Ποιο άρθρο ταιριάζει: ___ ${word}`
    const opts = mcOptions(article, ['ο', 'η', 'το'])
    addQ(grammar, 'grammar', 'multiple-choice', q, article, opts)
  }
}

function genGender(n) {
  const genderLabel = { ο: 'Αρσενικό', η: 'Θηλυκό', το: 'Ουδέτερο' }
  const chosen = pickN(NOUNS, Math.min(n, NOUNS.length))
  for (const [word, article] of chosen) {
    const q = `Ποιο είναι το γένος της λέξης «${word}»;`
    const answer = genderLabel[article]
    const opts = mcOptions(answer, ['Αρσενικό', 'Θηλυκό', 'Ουδέτερο'])
    addQ(grammar, 'grammar', 'multiple-choice', q, answer, opts)
  }
}

function genPluralText(n) {
  const chosen = pickN(NOUNS, Math.min(n, NOUNS.length))
  const pluralArticle = { ο: 'οι', η: 'οι', το: 'τα' }
  for (const [word, article, plural] of chosen) {
    const q = `Γράψε τον πληθυντικό αριθμό της λέξης «${article} ${word}».`
    addQ(grammar, 'grammar', 'text', q, `${pluralArticle[article]} ${plural}`)
  }
}

