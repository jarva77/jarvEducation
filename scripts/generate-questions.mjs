// ---------- seeded RNG ----------
function mulberry32(seed) {
  let a = seed
  return function () {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
const rng = mulberry32(20260901)
const randInt = (min, max) => Math.floor(rng() * (max - min + 1)) + min
const pick = (arr) => arr[randInt(0, arr.length - 1)]
function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = randInt(0, i)
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}
function pickN(arr, n) {
  return shuffle(arr).slice(0, n)
}

const seenQuestions = new Set()
let idCounters = { math: 0, grammar: 0, spelling: 0, environment: 0 }
// 'c' (Γ') or 'd' (Δ') — prefixes ids so feedback docs never collide across grades
let gradePrefix = 'c'

function addQ(bucket, category, type, question, answer, options, acceptedAnswers) {
  const key = category + '|' + question + '|' + answer
  if (seenQuestions.has(key)) return false
  seenQuestions.add(key)
  idCounters[category]++
  const q = {
    id: `${gradePrefix}-${category[0]}${idCounters[category]}`,
    category,
    type,
    question,
    answer: String(answer),
  }
  if (options) q.options = options
  if (acceptedAnswers?.length) q.acceptedAnswers = acceptedAnswers.map(String)
  bucket.push(q)
  return true
}

// Accepted variants for answers like "6€", "20 εκ.", "5:00" so kids
// aren't marked wrong for writing "6" or "20 εκατοστά".
function moneyAccepted(amount) {
  return [`${amount}`, `${amount} ευρώ`, `${amount}€`]
}
function cmAccepted(value) {
  return [`${value}`, `${value} εκ`, `${value} εκ.`, `${value} εκατοστά`]
}

function mcOptions(correct, distractors) {
  const uniqueDistractors = [...new Set(distractors.map(String))].filter((d) => d !== String(correct))
  return shuffle([String(correct), ...uniqueDistractors.slice(0, 3)])
}

