function genAddition(n, mcRatio) {
  let made = 0
  let guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const a = randInt(15, 850)
    const b = randInt(15, 999 - a)
    const sum = a + b
    const isMc = rng() < mcRatio
    const q = `Πόσο κάνει ${a} + ${b};`
    const opts = isMc
      ? mcOptions(sum, [sum + 10, sum - 10, sum + 1, sum - 100 > 0 ? sum - 100 : sum + 100])
      : undefined
    if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, sum, opts)) made++
  }
}

function genSubtraction(n, mcRatio) {
  let made = 0
  let guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const a = randInt(20, 950)
    const b = randInt(10, a)
    const diff = a - b
    const isMc = rng() < mcRatio
    const q = `Πόσο κάνει ${a} - ${b};`
    const opts = isMc
      ? mcOptions(diff, [diff + 10, diff - 10 >= 0 ? diff - 10 : diff + 20, diff + 1])
      : undefined
    if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, diff, opts)) made++
  }
}

function genMultiplication(n, mcRatio) {
  const facts = []
  for (let a = 2; a <= 10; a++) for (let b = 2; b <= 10; b++) facts.push([a, b])
  const chosen = pickN(facts, Math.min(n, facts.length))
  for (const [a, b] of chosen) {
    const prod = a * b
    const isMc = rng() < mcRatio
    const q = `Πόσο κάνει ${a} x ${b};`
    const opts = isMc ? mcOptions(prod, [prod + a, prod - a, prod + b]) : undefined
    addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, prod, opts)
  }
}

function genDivision(n, mcRatio) {
  const facts = []
  for (let b = 2; b <= 10; b++) for (let q = 2; q <= 10; q++) facts.push([b * q, b, q])
  const chosen = pickN(facts, Math.min(n, facts.length))
  for (const [dividend, divisor, quotient] of chosen) {
    const isMc = rng() < mcRatio
    const q = `Πόσο κάνει ${dividend} : ${divisor};`
    const opts = isMc ? mcOptions(quotient, [quotient + 1, quotient - 1, divisor]) : undefined
    addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, quotient, opts)
  }
}

function genRounding(n) {
  let made = 0, guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const toHundred = rng() < 0.4
    const num = toHundred ? randInt(105, 985) : randInt(11, 995)
    const base = toHundred ? 100 : 10
    const rounded = Math.round(num / base) * base
    const q = `Στρογγυλοποίησε τον αριθμό ${num} στην πλησιέστερη ${toHundred ? 'εκατοντάδα' : 'δεκάδα'}.`
    const opts = mcOptions(rounded, [rounded + base, rounded - base, num])
    if (addQ(math, 'math', 'multiple-choice', q, rounded, opts)) made++
  }
}

function genGeometry(n, mcRatio) {
  let made = 0, guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const kind = pick(['square', 'rectangle', 'shape'])
    if (kind === 'square') {
      const side = randInt(2, 25)
      const perim = side * 4
      const isMc = rng() < mcRatio
      const q = `Ένα τετράγωνο έχει πλευρά ${side} εκατοστά. Ποια είναι η περίμετρός του;`
      const opts = isMc ? mcOptions(perim + ' εκ.', [(perim + side) + ' εκ.', (perim - side) + ' εκ.', (side * 2) + ' εκ.']) : undefined
      if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, perim + ' εκ.', opts)) made++
    } else if (kind === 'rectangle') {
      const w = randInt(2, 20)
      const h = randInt(2, 20)
      if (w === h) continue
      const perim = 2 * (w + h)
      const isMc = rng() < mcRatio
      const q = `Ένα ορθογώνιο έχει πλευρές ${w} και ${h} εκατοστά. Ποια είναι η περίμετρός του;`
      const opts = isMc ? mcOptions(perim + ' εκ.', [(w * h) + ' εκ.', (perim + 2) + ' εκ.', (perim - 2) + ' εκ.']) : undefined
      if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, perim + ' εκ.', opts)) made++
    } else {
      const shapes = [['τρίγωνο', 3], ['τετράγωνο', 4], ['πεντάγωνο', 5], ['εξάγωνο', 6]]
      const [name, sides] = pick(shapes)
      const q = `Πόσες πλευρές έχει ένα ${name};`
      const opts = mcOptions(sides, [sides + 1, sides - 1, sides + 2])
      if (addQ(math, 'math', 'multiple-choice', q, sides, opts)) made++
    }
  }
}

function genMeasurement(n, mcRatio) {
  let made = 0, guard = 0
  const kinds = ['kg', 'm', 'l']
  while (made < n && guard < n * 20) {
    guard++
    const kind = pick(kinds)
    let q, ans, unit
    if (kind === 'kg') {
      const kg = randInt(1, 9)
      unit = 'γραμμάρια'
      ans = kg * 1000
      q = `Πόσα γραμμάρια είναι ${kg} κιλό${kg > 1 ? 'ά' : ''};`
    } else if (kind === 'm') {
      const m = randInt(1, 9)
      unit = 'εκατοστά'
      ans = m * 100
      q = `Πόσα εκατοστά είναι ${m} μέτρο${m > 1 ? 'α' : ''};`
    } else {
      const l = randInt(1, 9)
      unit = 'χιλιοστόλιτρα (ml)'
      ans = l * 1000
      q = `Πόσα χιλιοστόλιτρα (ml) είναι ${l} λίτρο${l > 1 ? 'α' : ''};`
    }
    const isMc = rng() < mcRatio
    const opts = isMc ? mcOptions(ans, [ans / 10, ans + 100, ans - 100]) : undefined
    if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, ans, opts)) made++
  }
}

function genTime(n, mcRatio) {
  let made = 0, guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const kind = pick(['minutes', 'days', 'elapsed'])
    let q, ans
    if (kind === 'minutes') {
      const h = randInt(1, 5)
      q = `Πόσα λεπτά είναι ${h} ώρ${h > 1 ? 'ες' : 'α'};`
      ans = h * 60
    } else if (kind === 'days') {
      const w = randInt(1, 5)
      q = `Πόσες ημέρες είναι ${w} εβδομάδ${w > 1 ? 'ες' : 'α'};`
      ans = w * 7
    } else {
      const startH = randInt(1, 10)
      const addH = randInt(1, 4)
      const endH = ((startH + addH - 1) % 12) + 1
      q = `Αν η ώρα είναι ${startH}:00, τι ώρα θα είναι σε ${addH} ώρες;`
      ans = `${endH}:00`
    }
    const isMc = rng() < mcRatio
    const opts = isMc ? mcOptions(ans, [Number(ans) ? Number(ans) + 10 : ans, Number(ans) ? Number(ans) - 10 : ans, Number(ans) ? Number(ans) + 1 : ans]) : undefined
    if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, ans, opts)) made++
  }
}

function genComparisonAndSequence(n, mcRatio) {
  let made = 0, guard = 0
  while (made < n && guard < n * 20) {
    guard++
    const kind = pick(['parity', 'sequence', 'place-value'])
    if (kind === 'parity') {
      const nums = pickN([randInt(10, 99), randInt(10, 99), randInt(10, 99), randInt(10, 99)], 4)
      const odds = nums.filter((x) => x % 2 !== 0)
      if (odds.length === 0 || odds.length === 4) continue
      const target = pick(rng() < 0.5 ? nums.filter((x) => x % 2 !== 0) : nums.filter((x) => x % 2 === 0))
      const isOdd = target % 2 !== 0
      const q = `Ποιος αριθμός είναι ${isOdd ? 'μονός (περιττός)' : 'ζυγός (άρτιος)'};`
      const opts = mcOptions(target, nums.filter((x) => x !== target))
      if (opts.length < 2) continue
      if (addQ(math, 'math', 'multiple-choice', q, target, opts)) made++
    } else if (kind === 'sequence') {
      const step = pick([2, 3, 5, 10])
      const start = randInt(1, 20) * step
      const seq = [start, start + step, start + 2 * step, start + 3 * step, start + 4 * step]
      const missingIdx = randInt(2, 3)
      const answer = seq[missingIdx]
      const display = seq.map((v, i) => (i === missingIdx ? '__' : v)).join(', ')
      const q = `Ποιος αριθμός λείπει: ${display};`
      const isMc = rng() < mcRatio
      const opts = isMc ? mcOptions(answer, [answer + step, answer - step, answer + 1]) : undefined
      if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', q, answer, opts)) made++
    } else {
      const h = randInt(1, 9)
      const t = randInt(0, 9)
      const u = randInt(0, 9)
      const num = h * 100 + t * 10 + u
      if (num < 100) continue
      const q = `Πόσες εκατοντάδες έχει ο αριθμός ${num};`
      const opts = mcOptions(h, [h + 1, h - 1 >= 0 ? h - 1 : h + 2, t])
      if (addQ(math, 'math', 'multiple-choice', q, h, opts)) made++
    }
  }
}

function genWordProblems(n, mcRatio) {
  let made = 0, guard = 0
  const templates = [
    () => {
      const name = pick(NAMES)
      const item = pick(ITEMS)
      const have = randInt(20, 90)
      const give = randInt(5, have - 5)
      const left = have - give
      return {
        q: `${fullName(name)} έχει ${have} ${item}. Δίνει ${give} σε έναν συμμαθητή. Πόσα ${item} μένουν;`,
        a: left,
      }
    },
    () => {
      const name = pick(NAMES)
      const item = pick(ITEMS)
      const price = randInt(1, 5)
      const count = randInt(2, 8)
      return {
        q: `${fullName(name)} αγόρασε ${count} ${item} των ${price}€ το καθένα. Πόσα ευρώ πλήρωσε συνολικά;`,
        a: `${price * count}€`,
      }
    },
    () => {
      const name = pick(NAMES)
      const item = pick(ITEMS)
      const total = randInt(20, 120)
      const groups = pick([2, 3, 4, 5, 6])
      if (total % groups !== 0) return null
      return {
        q: `${fullName(name)} έχει ${total} ${item} και τα μοιράζει εξίσου σε ${groups} φίλους. Πόσα ${item} παίρνει ο καθένας;`,
        a: total / groups,
      }
    },
    () => {
      const nameA = pick(NAMES)
      const nameB = pick(NAMES.filter((n) => n.name !== nameA.name))
      const item = pick(ITEMS)
      const a = randInt(10, 60)
      const b = randInt(10, 60)
      if (a === b) return null
      const diff = Math.abs(a - b)
      const more = a > b ? nameA : nameB
      return {
        q: `${fullName(nameA)} έχει ${a} ${item} και ${midSentenceName(nameB)} έχει ${b} ${item}. Πόσα ${item} περισσότερα έχει ${midSentenceName(more)};`,
        a: diff,
      }
    },
    () => {
      const name = pick(NAMES)
      const total = randInt(10, 50) * 2
      const frac = pick([2, 3, 4])
      if (total % frac !== 0) return null
      const eaten = total / frac
      const fracWord = frac === 2 ? 'το μισό' : frac === 3 ? 'το 1/3' : 'το 1/4'
      return {
        q: `${fullName(name)} έχει ${total} ${pick(ITEMS)}. Έφαγε ${fracWord}. Πόσα έφαγε;`,
        a: eaten,
      }
    },
    () => {
      const name = pick(NAMES)
      const price = randInt(2, 8)
      const paid = randInt(10, 20)
      if (paid <= price) return null
      return {
        q: `${fullName(name)} αγόρασε ένα παιχνίδι που κοστίζει ${price}€ και πλήρωσε με χαρτονόμισμα των ${paid}€. Πόσα ρέστα πήρε;`,
        a: `${paid - price}€`,
      }
    },
    () => {
      const name = pick(NAMES)
      const born = randInt(2016, 2019)
      const year = randInt(2026, 2029)
      return {
        q: `${fullName(name)} γεννήθηκε το ${born}. Πόσων χρονών θα είναι το ${year};`,
        a: year - born,
      }
    },
    () => {
      const name = pick(NAMES)
      const item = pick(ITEMS)
      const box = randInt(5, 12)
      const boxes = randInt(3, 9)
      return {
        q: `${fullName(name)} έχει ${boxes} κουτιά με ${box} ${item} το καθένα. Πόσα ${item} έχει συνολικά;`,
        a: box * boxes,
      }
    },
  ]
  while (made < n && guard < n * 30) {
    guard++
    const result = pick(templates)()
    if (!result) continue
    const isMc = rng() < mcRatio && typeof result.a !== 'string'
    let opts
    if (isMc) {
      const base = Number(result.a)
      opts = mcOptions(result.a, [base + randInt(1, 5), base - randInt(1, 5), base + 10])
    }
    if (addQ(math, 'math', isMc ? 'multiple-choice' : 'text', result.q, result.a, opts)) made++
  }
}

