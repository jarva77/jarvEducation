    const isMc = rng() < mcRatio
    const opts = isMc ? mcOptions(ans, [Number(ans) ? Number(ans) + 10 : ans, Number(ans) ? Number(ans) - 10 : ans, Number(ans) ? Number(ans) + 1 : ans]) : undefined
