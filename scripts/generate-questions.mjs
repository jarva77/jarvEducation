const CONFUSIONS = [
  ['ει', ['ι', 'η', 'οι']],
  ['οι', ['ι', 'η', 'ει']],
  ['αι', ['ε']],
  ['σσ', ['σ']],
  ['λλ', ['λ']],
  ['γγ', ['γκ']],
  ['ρρ', ['ρ']],
  ['ω', ['ο']],
  ['η', ['ι', 'υ']],
  ['ι', ['η', 'υ']],
  ['υ', ['η', 'ι']],
  ['ο', ['ω']],
]

function findConfusionMatch(word) {
  for (const [key, alts] of CONFUSIONS) {
    const idx = word.indexOf(key)
    if (idx !== -1) return { key, alts, idx }
  }
  return null
}

function buildSpellingVariants(word) {
  const match = findConfusionMatch(word)
  if (!match) return null
  const { key, alts, idx } = match
  const variants = alts
    .map((alt) => word.slice(0, idx) + alt + word.slice(idx + key.length))
    .filter((v) => v !== word)
  return variants.length ? { correct: word, wrongs: [...new Set(variants)] } : null
}

